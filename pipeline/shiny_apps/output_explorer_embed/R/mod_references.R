referencesUI <- function(id) {
  ns <- NS(id)
  tabPanel(
    title = "Write-up",
    br(),
    # Dark/light-aware styling for the rendered markdown previews. rgba(128,...)
    # greys read on both themes; links use the app accent blue. Long lines wrap
    # and wide tables scroll inside their own box.
    tags$head(tags$style(HTML("
      .gd-md { line-height:1.6; overflow-wrap:anywhere; }
      .gd-md h1,.gd-md h2,.gd-md h3,.gd-md h4 { line-height:1.25; margin:1.2em 0 .5em; }
      .gd-md h1{font-size:1.6em} .gd-md h2{font-size:1.35em} .gd-md h3{font-size:1.15em}
      .gd-md table { border-collapse:collapse; margin:1em 0; display:block; overflow-x:auto; }
      .gd-md th,.gd-md td { border:1px solid rgba(128,128,128,.4); padding:6px 10px; }
      .gd-md code { background:rgba(128,128,128,.18); padding:.1em .35em; border-radius:4px; }
      .gd-md pre { background:rgba(128,128,128,.15); padding:10px 12px; border-radius:6px; overflow-x:auto; }
      .gd-md pre code { background:none; padding:0; }
      .gd-md blockquote { margin:1em 0; padding:.4em 1em; border-left:3px solid rgba(128,128,128,.5); opacity:.9; }
      .gd-md a { color:#4ea1ff; }
      .gd-md img { max-width:100%; }
      .gd-writeup-note { color:#888; font-style:italic; margin:12px 0; }
    "))),
    # Clipboard copy: prefer the async API (secure + same-origin), fall back to a
    # hidden-textarea execCommand (works inside the cross-origin per-job iframe,
    # which lacks allow="clipboard-write"). Brief button feedback either way.
    tags$script(HTML("
      Shiny.addCustomMessageHandler('gd_copy', function(m){
        var btn = document.getElementById(m.btn);
        function flash(ok){ if(!btn) return; var t = btn.getAttribute('data-label') || btn.innerText;
          btn.setAttribute('data-label', t); btn.innerText = ok ? '✓ Copied' : 'Copy failed';
          setTimeout(function(){ btn.innerText = t; }, 1500); }
        function fallback(){ try { var ta=document.createElement('textarea'); ta.value=m.text;
          ta.style.position='fixed'; ta.style.top='0'; ta.style.left='0'; ta.style.opacity='0';
          document.body.appendChild(ta); ta.focus(); ta.select();
          var ok=document.execCommand('copy'); document.body.removeChild(ta); flash(ok); }
          catch(e){ flash(false); } }
        if (navigator.clipboard && navigator.clipboard.writeText && window.isSecureContext) {
          navigator.clipboard.writeText(m.text).then(function(){ flash(true); }, fallback);
        } else { fallback(); }
      });
    ")),
    uiOutput(ns("writeup_header")),
    tabsetPanel(
      id = ns("writeup_tabs"),
      tabPanel(
        "Methods",
        br(),
        uiOutput(ns("methods_actions")),
        div(class = "gd-md", uiOutput(ns("methods_html")))
      ),
      tabPanel(
        "Results",
        br(),
        uiOutput(ns("results_picker")),
        uiOutput(ns("results_actions")),
        div(class = "gd-md", uiOutput(ns("results_html")))
      ),
      tabPanel(
        "References",
        br(),
        p("Please be sure to cite the software and datasets used by this pipeline. Relevant citations are shown below:"),
        uiOutput(ns("bib_download")),
        fluidRow(
          column(width = 8, tableOutput(ns("reference_table")))
        )
      )
    )
  )
}

referencesServer <- function(id, gwas_data = NULL) {
  moduleServer(id, function(input, output, session) {
    ns <- session$ns

    muted <- function(txt) tags$p(class = "gd-writeup-note", txt)
    NA_MSG <- "Not available for results generated by this pipeline version."

    # The pipeline writes draft methods/results/reference files into the bundle at
    # package/writeup/. gwas_data() is the opened gd handle; gd$root_dir is the
    # package dir. Bundles produced before this feature (or where generation
    # failed) have no writeup/ dir -> NULL, and the sub-tabs show NA_MSG.
    writeup_dir <- reactive({
      if (is.null(gwas_data)) return(NULL)
      gd <- tryCatch(gwas_data(), error = function(e) NULL)
      if (is.null(gd) || is.null(gd$root_dir) || is.na(gd$root_dir)) return(NULL)
      d <- file.path(gd$root_dir, "writeup")
      if (dir.exists(d)) d else NULL
    })

    wu_path <- function(rel) {
      d <- writeup_dir(); if (is.null(d)) return(NULL)
      p <- file.path(d, rel); if (file.exists(p)) p else NULL
    }
    # Raw markdown text, faithfully (bytes -> UTF-8), for preview + copy. Downloads
    # use file.copy (byte-identical), never this.
    read_text <- function(rel) {
      p <- wu_path(rel); if (is.null(p)) return(NULL)
      txt <- readChar(p, file.info(p)$size, useBytes = TRUE)
      Encoding(txt) <- "UTF-8"
      txt
    }

    gwas_names <- reactive({
      gd <- tryCatch(gwas_data(), error = function(e) NULL)
      if (is.null(gd)) character(0) else gd_gwas(gd)
    })

    # ---- header (caveat + single Download all) -----------------------------
    output$writeup_header <- renderUI({
      if (is.null(writeup_dir())) return(NULL)
      tags$div(
        style = "border:1px solid rgba(128,128,128,.4); border-radius:6px; padding:12px 14px; margin-bottom:16px;",
        tags$strong("Draft write-up (automatically generated)"),
        tags$p(style = "margin:6px 0 10px;",
               "A draft methods section, descriptive results section and reference list generated from this run. ",
               tags$em("These are drafts — check and edit before use.")),
        downloadButton(ns("dl_all"), "Download all (.tar.gz)", class = "btn-sm")
      )
    })

    # ---- Methods sub-tab ----------------------------------------------------
    output$methods_html <- renderUI({
      txt <- read_text("methods.md")
      if (is.null(txt)) return(muted(NA_MSG))
      render_markdown_safe(txt)
    })
    output$methods_actions <- renderUI({
      if (is.null(wu_path("methods.md"))) return(NULL)
      tags$div(style = "margin-bottom:10px;",
        downloadButton(ns("dl_methods"), "Download .md", class = "btn-sm"),
        actionButton(ns("copy_methods"), "Copy raw markdown", class = "btn-sm")
      )
    })

    # ---- Results sub-tab ----------------------------------------------------
    # Local single-select GWAS picker (NOT the shared control rail). Suppressed
    # for single-GWAS bundles, where there's nothing to pick between.
    output$results_picker <- renderUI({
      g <- gwas_names()
      if (length(g) < 2L) return(NULL)
      cur <- isolate(input$results_gwas)
      keep <- if (!is.null(cur) && cur %in% g) cur else g[1L]
      div(style = "max-width:420px; margin-bottom:10px;",
        selectInput(ns("results_gwas"), "GWAS:",
                    choices = gwas_choices(gwas_data(), g),
                    selected = keep, multiple = FALSE, width = "100%"))
    })

    res_gwas <- reactive({
      g <- gwas_names()
      if (!length(g)) return(NULL)
      sel <- input$results_gwas
      if (!is.null(sel) && sel %in% g) sel else g[1L]
    })

    res_rel <- reactive({
      g <- res_gwas(); if (is.null(g)) return(NULL)
      file.path(g, "results.md")
    })

    output$results_html <- renderUI({
      rel <- res_rel(); if (is.null(rel)) return(muted(NA_MSG))
      txt <- read_text(rel)
      if (is.null(txt)) return(muted(NA_MSG))
      render_markdown_safe(txt)
    })
    output$results_actions <- renderUI({
      rel <- res_rel()
      if (is.null(rel) || is.null(wu_path(rel))) return(NULL)
      tags$div(style = "margin-bottom:10px;",
        downloadButton(ns("dl_results"), "Download .md", class = "btn-sm"),
        actionButton(ns("copy_results"), "Copy raw markdown", class = "btn-sm")
      )
    })

    # ---- copy-to-clipboard (sends raw markdown, never rendered HTML) --------
    observeEvent(input$copy_methods, {
      txt <- read_text("methods.md"); req(txt)
      session$sendCustomMessage("gd_copy", list(text = txt, btn = ns("copy_methods")))
    })
    observeEvent(input$copy_results, {
      rel <- res_rel(); req(rel)
      txt <- read_text(rel); req(txt)
      session$sendCustomMessage("gd_copy", list(text = txt, btn = ns("copy_results")))
    })

    # ---- downloads (byte-identical file.copy) ------------------------------
    output$dl_methods <- downloadHandler(
      filename = function() "genodisc_draft_methods.md",
      content  = function(file) { p <- wu_path("methods.md"); req(p); file.copy(p, file, overwrite = TRUE) }
    )
    output$dl_results <- downloadHandler(
      filename = function() {
        g <- res_gwas(); if (is.null(g)) "genodisc_results.md" else paste0("genodisc_results_", g, ".md")
      },
      content  = function(file) { rel <- res_rel(); req(rel); p <- wu_path(rel); req(p); file.copy(p, file, overwrite = TRUE) }
    )
    output$dl_bib <- downloadHandler(
      filename = function() "genodisc_references.bib",
      content  = function(file) { p <- wu_path("references.bib"); req(p); file.copy(p, file, overwrite = TRUE) }
    )
    output$dl_all <- downloadHandler(
      filename = function() "genodisc_draft_writeup.tar.gz",
      content  = function(file) {
        d <- writeup_dir(); req(d)
        old <- setwd(dirname(d)); on.exit(setwd(old), add = TRUE)
        utils::tar(file, basename(d), compression = "gzip")
      }
    )

    # ---- References sub-tab -------------------------------------------------
    output$bib_download <- renderUI({
      if (is.null(wu_path("references.bib"))) return(NULL)
      tags$div(style = "margin-bottom:12px;",
               downloadButton(ns("dl_bib"), "Download .bib", class = "btn-sm"))
    })

    # Static citations table (plain renderTable, not DT - no sorting/search needed).
    # Name links to the tool/dataset website; the PMID / DOI column links to
    # PubMed or doi.org. HTML anchors render via sanitize.text.function = identity.
    output$reference_table <- renderTable({
      cite <- function(name, website, pmid_doi, type, use) data.frame(
        Name = sprintf('<a href="%s">%s</a>', website, name),
        `PMID / DOI` = pmid_doi, Type = type, Use = use,
        check.names = FALSE, stringsAsFactors = FALSE)
      pubmed <- function(id) sprintf('<a href="https://pubmed.ncbi.nlm.nih.gov/%s">%s</a>', id, id)
      doi    <- function(d)  sprintf('<a href="https://doi.org/%s">%s</a>', d, d)

      rbind(
        cite('LD Score Regression', 'https://github.com/bulik/ldsc', pubmed('25642630'), 'Software', 'Estimate SNP-h2 and LD-score intercept'),
        cite('SBayesRC', 'https://github.com/zhilizheng/SBayesRC', pubmed('38689000'), 'Software', 'Estimate SNP-h2, polygenicity and functional-annotation heritability enrichment'),
        cite('SumHer (LDAK)', 'https://dougspeed.com/', pubmed('30510236'), 'Software', 'Estimate SNP-h2 and functional-annotation heritability enrichment (BLD-LDAK model)'),
        cite('Manc-COJO', 'https://github.com/light156/multi-ancestry-COJO', doi('10.1038/s41588-026-02799-1'), 'Software', 'Conditional & joint analysis for independent association signals'),
        cite('SuSiE', 'https://stephenslab.github.io/susie-paper', pubmed('35853082'), 'Software', 'Variant-level finemapping'),
        cite('FUSION', 'http://gusevlab.org/projects/fusion/', pubmed('26854917'), 'Software', 'Perform TWAS/PWAS'),
        cite('COLOC', 'https://chr1swallace.github.io/coloc/', pubmed('24830394'), 'Software', 'Used for colocalisation within FUSION TWAS/PWAS analysis'),
        cite('SMR', 'https://yanglab.westlake.edu.cn/software/smr/#Overview', pubmed('29763751'), 'Software', 'Infer differential expression or protein levels'),
        cite('MAGMA', 'https://ctg.cncr.nl/software/magma', pubmed('25885710'), 'Software', 'Estimate gene associations and drug enrichment using DrugTargetor database'),
        cite('TWAS-GSEA', 'https://github.com/opain/TWAS-GSEA', pubmed('31230729'), 'Software', 'Estimate drug enrichment using TWAS and DrugTargetor'),
        cite('PsychENCODE DLPFC TWAS SNP-weights', 'http://resource.psychencode.org/', pubmed('30545856'), 'Dataset', 'TWAS'),
        cite('PsychENCODE DLPFC eQTL data for SMR', 'http://cnsgenomics.com/data/SMR/', pubmed('30545857'), 'Dataset', 'SMR'),
        cite('MetaBrain eQTL data for SMR', 'https://www.metabrain.nl/cis-eqtls.html', pubmed('36823318'), 'Dataset', 'SMR'),
        cite('ROSMAP/Banner DLPFC PWAS SNP-weights and eQTL in SMR results', 'https://www.synapse.org/#!Synapse:syn23627957', pubmed('33510477'), 'Dataset', 'PWAS and SMR'),
        cite('DrugTargetor', 'https://drugtargetor.com/', pubmed('30517594'), 'Dataset', 'Drug repurposing'),
        cite('PoPS (Polygenic Priority Score)', 'https://github.com/FinucaneLab/pops', pubmed('37443254'), 'Software', 'Gene prioritisation (Ensembl-ID MAGMA step feeding CALDERA)'),
        cite('CALDERA', 'https://github.com/kheilbron/caldera', doi('10.1371/journal.pgen.1012079'), 'Software', 'Effector-gene prioritisation from fine-mapped credible sets'),
        cite('BCFtools/csq', 'http://samtools.github.io/bcftools/', pubmed('28205675'), 'Software', 'Haplotype-aware variant consequence annotation (credible-set coding)'),
        cite('AlphaMissense', 'https://github.com/google-deepmind/alphamissense', pubmed('37733863'), 'Dataset', 'Missense pathogenicity scores for credible-set coding variants'),
        cite('GENCODE', 'https://www.gencodegenes.org/', pubmed('33270111'), 'Dataset', "Protein-coding gene model (CALDERA's gene universe)")
      )
    }, sanitize.text.function = function(x) x, rownames = FALSE)
  })
}
